# Task 2 & 3: FGSM and PGD Attacks

def fgsm_attack(image, epsilon, data_grad):
    sign_data_grad = data_grad.sign()
    pert_img = image + epsilon * sign_data_grad
    pert_img = torch.clamp(pert_img, 0, 1)
    return pert_img

def pgd_attack(model, image, label, epsilon, alpha=0.01, num_iter=10):
    pert_img = image.clone().detach().requires_grad_(True)
    for _ in range(num_iter):
        outputs = model(pert_img)
        loss = criterion(outputs, label)
        model.zero_grad()
        loss.backward()

        # Gradient ascent step
        with torch.no_grad():
            adv_image = pert_img + alpha * pert_img.grad.sign()
            eta = torch.clamp(adv_image - image, min=-epsilon, max=epsilon)
            pert_img = torch.clamp(image + eta, min=0, max=1).detach().requires_grad_(True)

    return pert_img

def test_attacks(model, loader, epsilons):
    fgsm_accs = []
    pgd_accs = []

    for eps in epsilons:
        fgsm_correct = 0
        pgd_correct = 0
        total = 0

        for images, labels in loader:
            images, labels = images.to(device), labels.to(device)

            # --- FGSM Attack ---
            images.requires_grad = True
            outputs = model(images)
            loss = criterion(outputs, labels)
            model.zero_grad()
            loss.backward()
            data_grad = images.grad.data

            pert_imgs_fgsm = fgsm_attack(images, eps, data_grad)
            with torch.no_grad():
                outputs_fgsm = model(pert_imgs_fgsm)
                _, pred_fgsm = torch.max(outputs_fgsm, 1)
                fgsm_correct += (pred_fgsm == labels).sum().item()

            # --- PGD Attack ---
            pert_imgs_pgd = pgd_attack(model, images, labels, eps, alpha=0.01 if eps > 0 else 0, num_iter=10)
            with torch.no_grad():
                outputs_pgd = model(pert_imgs_pgd)
                _, pred_pgd = torch.max(outputs_pgd, 1)
                pgd_correct += (pred_pgd == labels).sum().item()

            total += labels.size(0)

        fgsm_acc = (fgsm_correct / total) * 100
        pgd_acc = (pgd_correct / total) * 100
        fgsm_accs.append(fgsm_acc)
        pgd_accs.append(pgd_acc)
        print(f"Epsilon: {eps:.2f} | FGSM Accuracy: {fgsm_acc:.2f}% | PGD Accuracy: {pgd_acc:.2f}%")

    return fgsm_accs, pgd_accs

epsilons = [0.00, 0.05, 0.15, 0.30]
